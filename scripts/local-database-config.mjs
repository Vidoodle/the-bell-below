import { createHash, randomBytes } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const configPath = resolve(".env.database.local");
const databaseName = "bell_below_dev";
const databaseUser = "bell_below";

function hasCode(error, code) {
  return error !== null && typeof error === "object" && "code" in error && error.code === code;
}

function expectedProjectName() {
  const path = process.platform === "win32" ? resolve(".").toLowerCase() : resolve(".");
  const projectHash = createHash("sha256").update(path).digest("hex").slice(0, 8);
  return `bell-below-dev-${projectHash}`;
}

function parse(contents) {
  const values = Object.fromEntries(contents
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => {
      const separator = line.indexOf("=");
      return separator < 1 ? [] : [line.slice(0, separator), line.slice(separator + 1)];
    })
    .filter((entry) => entry.length === 2));
  const databaseUrl = values.DATABASE_URL;
  const password = values.BELL_BELOW_DB_PASSWORD;
  const projectName = values.BELL_BELOW_COMPOSE_PROJECT;
  if (!databaseUrl || !password || !projectName) {
    throw new Error(".env.database.local is incomplete. Remove it and run 'pnpm db:setup' to regenerate it.");
  }

  const url = new URL(databaseUrl);
  const validUrl = url.protocol === "postgresql:"
    && url.hostname === "127.0.0.1"
    && url.port === "5432"
    && url.pathname === `/${databaseName}`
    && url.username === databaseUser
    && url.password === password;
  if (!validUrl || projectName !== expectedProjectName()) {
    throw new Error(".env.database.local does not describe a valid repository-managed development database.");
  }
  return {
    databaseUrl,
    password,
    projectName,
    volumeName: `${projectName}_postgres-dev-data`,
  };
}

export async function readLocalDatabaseConfig() {
  try {
    return parse(await readFile(configPath, "utf8"));
  } catch (error) {
    if (hasCode(error, "ENOENT")) {
      throw new Error(".env.database.local is missing. Run 'pnpm db:setup' to create it.");
    }
    throw error;
  }
}

export async function ensureLocalDatabaseConfig() {
  let existing;
  try {
    existing = await readFile(configPath, "utf8");
  } catch (error) {
    if (!hasCode(error, "ENOENT")) throw error;
  }
  if (existing !== undefined) return parse(existing);

  const password = randomBytes(24).toString("hex");
  const projectName = expectedProjectName();
  const databaseUrl = `postgresql://${databaseUser}:${password}@127.0.0.1:5432/${databaseName}`;
  const contents = [
    "# Generated by pnpm db:setup. Do not commit this file.",
    `DATABASE_URL=${databaseUrl}`,
    `BELL_BELOW_DB_PASSWORD=${password}`,
    `BELL_BELOW_COMPOSE_PROJECT=${projectName}`,
    "",
  ].join("\n");
  try {
    await writeFile(configPath, contents, { encoding: "utf8", flag: "wx", mode: 0o600 });
  } catch (error) {
    if (!hasCode(error, "EEXIST")) throw error;
  }
  return readLocalDatabaseConfig();
}
